"""Generate the Lua name catalog for Heavy Kill Notice.

Merges:
  - BFV Kill Feedback  TYPE_KIND_BY_RUNTIME (decimal type -> light/medium/heavy/flying)
  - DeathSourceNotice  catalog (hex type -> en/zh/faction/kind)

Writes src/catalog_gen.lua, a single Lua block defining:
    local CATALOG = { [hex] = {en=.., zh=.., kind=.., heavy=true?} , ... }
    local HEAVY = { [hex] = true, ... }
"""
import re, os

BFV = r'D:\SteamLibrary\steamai\HD2Tools\work\bfv\000_mods_test_author_battlefield5_kill_feedback.lua'
DSN = r'D:\SteamLibrary\steamai\HD2Tools\work\deathsourcenotice\lua\000_mods_hanhua_teamkill_notice.lua'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'src', 'catalog_gen.lua')

bfv = open(BFV, encoding='utf-8', errors='replace').read()
dsn = open(DSN, encoding='utf-8', errors='replace').read()

kind = {}
for m in re.finditer(r'TYPE_KIND_BY_RUNTIME\["(\d+)"\]\s*=\s*"(\w+)"', bfv):
    kind[format(int(m.group(1)), '016X')] = m.group(2)

cat = {}
for m in re.finditer(r'\["([0-9A-F]{16})"\]=\{en="([^"]*)",zh="([^"]*)",faction="([^"]*)",kind="([^"]*)"\}', dsn):
    cat[m.group(1)] = {'en': m.group(2), 'zh': m.group(3), 'faction': m.group(4), 'kind': m.group(5)}


def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


lines = ['-- GENERATED by gen_catalog.py -- do not edit', 'local CATALOG={']
heavy = []
for hx in sorted(cat):
    c = cat[hx]
    k = kind.get(hx)
    heavy_flag = (k == 'heavy') or (k == 'flying' and c['kind'] == 'enemy' and False)
    if k == 'heavy':
        heavy.append(hx)
    extra = ''
    if k:
        extra += 'kind="%s",' % k
    if k == 'heavy':
        extra += 'heavy=true,'
    lines.append('["%s"]={en="%s",zh="%s",faction="%s",kind2="%s",%s},' %
                 (hx, esc(c['en']), esc(c['zh']), esc(c['faction']), esc(c['kind']), extra))
# BFV types that have no DSN name (keep the heavy ones)
for hx, k in sorted(kind.items()):
    if hx not in cat and k == 'heavy':
        heavy.append(hx)
        lines.append('["%s"]={en="heavy unit",zh="重甲单位",faction="",kind2="enemy",kind="heavy",heavy=true,},' % hx)
lines.append('}')
lines.append('local HEAVY={')
for hx in sorted(set(heavy)):
    lines.append('["%s"]=true,' % hx)
lines.append('}')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print('wrote', OUT, os.path.getsize(OUT), 'bytes;', len(cat), 'catalog,', len(set(heavy)), 'heavy')
